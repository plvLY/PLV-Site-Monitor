import { describe, it, expect, vi } from "vitest";
import { generateEventId } from "../../src/events/event-id";

describe("generateEventId", () => {
  it("EVT-ID-01: should generate a valid UUID v4", () => {
    const eventId = generateEventId();

    expect(eventId).toMatch(
      /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i
    );
  });

  it("EVT-ID-02: should generate unique IDs", () => {
    const first = generateEventId();
    const second = generateEventId();

    expect(first).not.toBe(second);
  });

  it("EVT-ID-03: should use crypto.randomUUID when available", () => {
    const expectedId = "accb07ee-6504-4855-b25b-4a5bf22d8164";

    vi.stubGlobal("crypto", {
      randomUUID: vi.fn(() => expectedId),
    });

    expect(generateEventId()).toBe(expectedId);
  });

  it("EVT-ID-04: should fallback to crypto.getRandomValues", () => {
    vi.stubGlobal("crypto", {
      getRandomValues: (array: Uint8Array) => {
        array.set([
          0x11, 0x22, 0x33, 0x44,
          0x55, 0x66, 0x00, 0x77,
          0x88, 0x99, 0xaa, 0xbb,
          0xcc, 0xdd, 0xee, 0xff,
        ]);
        return array;
      },
    });

    const eventId = generateEventId();

    expect(eventId).toBe(
      "11223344-5566-4077-8899-aabbccddeeff"
    );
  });

  it("EVT-ID-05: should throw when secure crypto is unavailable", () => {
    vi.stubGlobal("crypto", undefined);

    expect(() => generateEventId()).toThrow(
      "Secure event ID generation is not supported."
    );
  });

  it("EVT-ID-06: should reject invalid UUID generated by crypto", () => {
    vi.stubGlobal("crypto", {
      randomUUID: vi.fn(() => "invalid-uuid"),
    });

    expect(() => generateEventId()).toThrow(
      "Generated event ID is not a valid UUID v4."
    );
  });
});
